#!/usr/bin/env python3
"""Write data/large/MANIFEST.md from the CSV files present and the verification reports in data/large/logs/."""
import json
import os
import sys
import time

root = os.path.abspath(sys.argv[1])


def load(name):
    p = os.path.join(root, "logs", name)
    out = {}
    if os.path.exists(p):
        for line in open(p):
            r = json.loads(line)
            out[r.get("file") or r.get("table") + ".csv"] = r  # later lines win
    return out


def gb(b):
    return f"{b / 1e9:.2f} GB"


lines = [f"# Large datasets for the pruning-opportunity study", "",
         f"Generated by the scripts in `pruning_opportunity/datagen/` (see their docstrings); manifest written "
         f"{time.strftime('%Y-%m-%d %H:%M')}. Row counts exclude the header line. Verification reports (JSON "
         f"lines) and generation logs are in `logs/`.", ""]
reports = {"micro": load("verify_micro.jsonl"), "tpch": load("verify_tpch.jsonl"),
           "tpcds": load("verify_tpcds.jsonl")}
total = 0
for d in ["micro", "tpch", "tpcds"]:
    path = os.path.join(root, d)
    if not os.path.isdir(path):
        continue
    files = sorted(f for f in os.listdir(path) if f.endswith(".csv"))
    lines += [f"## {d}/", "", "| file | rows | size | verified | details |", "|---|---:|---:|---|---|"]
    for f in files:
        size = os.path.getsize(os.path.join(path, f))
        total += size
        r = reports[d].get(f, {})
        rows = r.get("rows", "")
        ok = {True: "OK", False: "FAILED"}.get(r.get("ok"), "not verified")
        det = []
        if d == "micro":
            if "time_min" in r:
                det.append(f"time [{r['time_min']}, {r['time_max']}], data [{r['data_min']}, {r['data_max']}]")
            if "fingerprint_matches_sorted_bin" in r:
                det.append("multiset == sorted" if r["fingerprint_matches_sorted_bin"] else "multiset MISMATCH")
            if r.get("kind") == "sorted":
                det.append("non-decreasing (time,data), equals sorted keys")
            if r.get("kind") == "outliers":
                det.append("every row checked against outlier placement formula")
            if "partitions" in r:
                det.append(f"{r['partitions']} partitions, distinct ids/partition min {r['distinct_min']} "
                           f"max {r['distinct_max']} mean {r['distinct_mean']}; time == sorted.csv time")
        else:
            if "load_seconds" in r:
                det.append(f"loads with repo DDL+COPY ({r['load_seconds']} s)")
            if "orderkey_decreases" in r:
                det.append(f"orderkey non-decreasing in file order (range {r['orderkey_range']})")
            if "null_cells" in r:
                det.append(f"content == dsdgen reference (per-column hashes, {r['null_cells']} NULL cells); "
                           f"first {r['order_prefix_rows_checked']} rows in dsdgen order")
        det += r.get("errors", [])
        rows_s = f"{rows:,}" if isinstance(rows, int) else rows
        lines.append(f"| `{f}` | {rows_s} | {gb(size)} | {ok} | {'; '.join(det)} |")
    lines.append("")
lines.append(f"Total size: {gb(total)}")
lines.append("")
with open(os.path.join(root, "MANIFEST.md"), "w") as f:
    f.write("\n".join(lines))
print("\n".join(lines))
