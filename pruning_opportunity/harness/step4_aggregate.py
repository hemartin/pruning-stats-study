#!/usr/bin/env python3
"""Step 4 aggregation (run_large_step4.sh): baseline (min/max) vs. new version on persistent databases.

Reads results/raw/<scale>/phase4/<config>/{count,time}/<group>/ for the step-4 configs (phase4.py --attach-existing;
statistics built while ATTACH loads the table, PRUNING_STATS_BUILD_ON_LOAD) and writes
results/<scale>/phase4/step4/{pruning.csv,build.csv,timing_per_query.csv,timing_per_setup.csv,summary.md}:

* observed pruning (count mode): per setup and config, row groups total / pruned by min/max / by the selective
  statistic / by the predicate cache / by the row-id range check / wasted (scanned, no rows) / with rows; ClickBench
  per pass (cold / warm predicate cache);
* statistic build cost (the ATTACH item): wall time of ATTACH (new - baseline = build overhead), build CPU time
  (sort/encode, all threads), key extraction, data read, bytes, row groups;
* lookup cost on top of min/max (time mode): consult_ns (selective statistics) + pc_lookup_ns (predicate cache)
  per query, all threads;
* end-to-end: per query median over the rounds (ClickBench: cold = round 1, warm = median of rounds 2..R),
  per setup sum and speedup baseline / new.
"""
import argparse
import collections
import csv
import glob
import json
import os
import statistics
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common  # noqa: E402
import phase4  # noqa: E402

# (group pattern, baseline config, [new configs])
DEFAULT_PAIRS = "micro_*:baseline_step4:occts200_step4,nsts200_step4;clickbench:baseline_step4cb:cbnew_step4"


def gdirs(scale, config, mode):
    base = os.path.join(common.raw_dir(scale, "phase4"), config, mode)
    return sorted(d for d in glob.glob(os.path.join(base, "*")) if os.path.isdir(d))


def load_group(d):
    """-> scans[tag] (last execution), timing[tag] (query_timing), ingest records, load_build, status"""
    scans, timing, ingest, load_build, status = collections.defaultdict(list), {}, [], [], {}
    for a in sorted(glob.glob(os.path.join(d, "session_*", "attempt_*"))):
        cur = {}
        for r in phase4.load_jsonl(os.path.join(a, "pruning.jsonl")):
            tag = r.get("tag", "")
            if not tag or "/ingest/" in tag:
                continue
            if r["type"] == "query" and not r["sql"].startswith("SET"):
                cur[tag] = r["seq"]
                scans[tag] = []
            elif r["type"] == "scan" and cur.get(tag) == r["seq"]:
                scans[tag].append(r)
        for r in phase4.load_jsonl(os.path.join(a, "timing.jsonl")):
            t = r.get("type")
            if t == "query_timing" and r.get("tag") and "/ingest/" not in r["tag"] and not r["sql"].startswith("SET"):
                timing[r["tag"]] = r
            elif t == "ingest":
                ingest.append(r)
            elif t == "load_build":
                load_build.append(r)
            elif t == "query_timing" and r.get("tag", "").endswith("/ingest/attach"):
                ingest.append(dict(r, type="attach_timing"))
        for r in phase4.load_jsonl(os.path.join(a, "status.jsonl")):
            status[r["tag"]] = r
    return scans, timing, ingest, load_build, status


def split(tag):
    """'point_unsorted/q0005#r2' -> (setup, qid, k) with k = round or pass (1 if none)"""
    setup, rest = tag.split("/", 1)
    for sep in ("#r", "#p"):
        if sep in rest:
            q, k = rest.split(sep)
            return setup, q, int(k)
    return setup, rest, 1


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--scale", default="large")
    ap.add_argument("--pairs", default=DEFAULT_PAIRS,
                    help="group_glob:baseline:new1,new2;... (default: %(default)s)")
    ap.add_argument("--out", default="")
    args = ap.parse_args()
    out = args.out or os.path.join(common.results_dir(args.scale), "phase4", "step4")
    os.makedirs(out, exist_ok=True)
    import fnmatch
    pairs = []
    for p in args.pairs.split(";"):
        g, b, n = p.split(":")
        pairs.append((g, b, n.split(",")))

    prune_rows, build_rows, tq_rows, ts_rows = [], [], [], []
    md = ["# Step 4: baseline (min/max) vs. new version, scale `%s`" % args.scale, "",
          "Generated by `harness/step4_aggregate.py`. Persistent databases attached read-only "
          "(`phase4.py --attach-existing`); the new version's statistics are built while ATTACH loads the table "
          "(`PRUNING_STATS_BUILD_ON_LOAD`), i.e. the ATTACH time difference is the statistic build cost.", ""]
    for gpat, base, news in pairs:
        configs = [base] + news
        groups = sorted({os.path.basename(d) for c in configs for m in ("count", "time")
                         for d in gdirs(args.scale, c, m) if fnmatch.fnmatch(os.path.basename(d), gpat)})
        for g in groups:
            md += ["## %s" % g, ""]
            data = {}
            for c in configs:
                for m in ("count", "time"):
                    d = os.path.join(common.raw_dir(args.scale, "phase4"), c, m, g)
                    data[(c, m)] = load_group(d) if os.path.isdir(d) else None
            # ---------------- pruning (count)
            md += ["### Observed pruning (count mode)", "",
                   "| setup | pass | config | queries | row groups | pruned min/max | statistic | pred. cache | "
                   "rowid | wasted | with rows | partial + not reached |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
            for c in configs:
                dd = data.get((c, "count"))
                if not dd:
                    continue
                agg = collections.defaultdict(collections.Counter)
                for tag, ss in dd[0].items():
                    setup, q, k = split(tag)
                    a = agg[(setup, k)]
                    a["queries"] += 1
                    for s in ss:
                        a["total"] += s["total_row_groups"]
                        a["rowid"] += s.get("pruned_rowid_only", 0)
                        a["minmax"] += s["pruned_minmax"] - s.get("pruned_rowid_only", 0)
                        a["stat"] += s["pruned_additional"]
                        a["pc"] += s.get("pruned_predicate_cache", 0)
                        a["wasted"] += s["scanned_no_rows"]
                        a["with"] += s["scanned_with_rows"]
                        a["rest"] += s["partial_no_rows"] + s["not_reached"]
                for (setup, k), a in sorted(agg.items()):
                    row = {"group": g, "setup": setup, "pass": k, "config": c, **a}
                    prune_rows.append(row)
                    md.append("| %s | %s | %s | %d | %d | %d | %d | %d | %d | %d | %d | %d |" % (
                        setup, {1: "1 (cold)", 2: "2 (warm)"}.get(k, k), c, a["queries"], a["total"], a["minmax"],
                        a["stat"], a["pc"], a["rowid"], a["wasted"], a["with"], a["rest"]))
            # ---------------- build (attach item, both modes)
            md += ["", "### Statistic build at load (ATTACH)", "",
                   "| config | mode | ATTACH wall s | build CPU s (sort/encode) | key extraction s | data read s | "
                   "load_build wall s | threads | statistics | bytes |", "|---|---|---|---|---|---|---|---|---|---|"]
            for c in configs:
                for m in ("count", "time"):
                    dd = data.get((c, m))
                    if not dd:
                        continue
                    st = [r for t, r in dd[4].items() if t.endswith("/ingest/attach")]
                    wall = st[-1]["wall_s"] if st else None
                    ing = [r for r in dd[2] if r["type"] == "ingest"]
                    lb = dd[3]
                    b = {"group": g, "config": c, "mode": m, "attach_wall_s": wall,
                         "build_s": sum(r["build_ns"] for r in ing) / 1e9,
                         "buffer_s": sum(r["buffer_ns"] for r in ing) / 1e9,
                         "read_s": sum(r["read_ms"] for r in lb) / 1e3,
                         "load_build_wall_s": sum(r["wall_ms"] for r in lb) / 1e3,
                         "threads": max([r["threads"] for r in lb] or [0]),
                         "stats": sum(r["row_groups_built"] for r in ing),
                         "bytes": sum(r["bytes"] for r in ing),
                         "columns": ";".join(sorted({"%s:%s" % (r["column"], r["kind"]) for r in ing}))}
                    build_rows.append(b)
                    md.append("| %s | %s | %s | %.1f | %.1f | %.1f | %.1f | %d | %d | %d |" % (
                        c, m, "%.1f" % wall if wall is not None else "-", b["build_s"], b["buffer_s"], b["read_s"],
                        b["load_build_wall_s"], b["threads"], b["stats"], b["bytes"]))
            # ---------------- timing
            tdata = {}
            for c in configs:
                dd = data.get((c, "time"))
                if not dd:
                    continue
                per = collections.defaultdict(dict)
                for tag, r in dd[1].items():
                    setup, q, k = split(tag)
                    per[(setup, q)][k] = r
                tdata[c] = per
            if not tdata:
                md += ["", "(no time-mode data)", ""]
                continue
            is_cb = g == "clickbench"
            md += ["", "### End-to-end time (time mode; engine-side ms)", "",
                   ("ClickBench: cold = round 1 (empty predicate cache), warm = median of rounds 2..R. "
                    if is_cb else "Median over the rounds per query. ") +
                   "Lookup = selective-statistic consultation + predicate-cache lookup, CPU summed over threads, "
                   "per query (median over rounds).", "",
                   "| setup | config | queries | sum of %s ms | speedup vs. %s | lookup ms / query |" % (
                       "warm medians" if is_cb else "medians", base) + (" sum of cold ms |" if is_cb else ""),
                   "|---|---|---|---|---|---|" + ("---|" if is_cb else "")]
            setups = sorted({s for c in tdata for (s, q) in tdata[c]})
            for setup in setups:
                sums = {}
                for c in configs:
                    if c not in tdata:
                        continue
                    qs = sorted(q for (s, q) in tdata[c] if s == setup)
                    tot, cold_tot, lookup = 0.0, 0.0, []
                    n = 0
                    for q in qs:
                        rr = tdata[c][(setup, q)]
                        ks = sorted(rr)
                        warm_ks = [k for k in ks if k > 1] if is_cb and len(ks) > 1 else ks
                        med = statistics.median(rr[k]["elapsed_ms"] for k in warm_ks)
                        lk = statistics.median((rr[k].get("consult_ns", 0) + rr[k].get("pc_lookup_ns", 0)) / 1e6
                                               for k in warm_ks)
                        cold = rr[ks[0]]["elapsed_ms"]
                        tot += med
                        cold_tot += cold
                        lookup.append(lk)
                        n += 1
                        tq_rows.append({"group": g, "setup": setup, "qid": q, "config": c, "median_ms": round(med, 3),
                                        "cold_ms": round(cold, 3), "lookup_ms": round(lk, 4), "rounds": len(ks)})
                    sums[c] = (n, tot, cold_tot, statistics.mean(lookup) if lookup else 0.0)
                for c, (n, tot, cold_tot, lk) in sums.items():
                    sp = sums[base][1] / tot if base in sums and tot > 0 else float("nan")
                    ts_rows.append({"group": g, "setup": setup, "config": c, "queries": n, "sum_ms": round(tot, 1),
                                    "cold_sum_ms": round(cold_tot, 1), "speedup": round(sp, 3),
                                    "lookup_ms_per_query": round(lk, 3)})
                    md.append("| %s | %s | %d | %.1f | %.2f | %.3f |%s" % (
                        setup, c, n, tot, sp, lk, (" %.1f |" % cold_tot) if is_cb else ""))
            md.append("")
    for name, rows in (("pruning.csv", prune_rows), ("build.csv", build_rows), ("timing_per_query.csv", tq_rows),
                       ("timing_per_setup.csv", ts_rows)):
        if rows:
            keys = []
            for r in rows:
                keys += [k for k in r if k not in keys]
            with open(os.path.join(out, name), "w", newline="") as f:
                w = csv.DictWriter(f, fieldnames=keys)
                w.writeheader()
                w.writerows(rows)
    with open(os.path.join(out, "summary.md"), "w") as f:
        f.write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
